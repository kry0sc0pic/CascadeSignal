    def positions_at_many(self, keys: pd.DataFrame) -> pd.DataFrame:
        """Batch equivalent of `positions_at` for many (user, block_number)
        pairs at once. `keys` has columns `user`, `block_number`, and
        optionally `query_timestamp` (CAS-28 H5) -- if present, forward-
        compounds the interest index from its last on-chain write to that
        exact per-row moment (see `_reinflate`) instead of using the value
        stored as of `block_number` only.

        Naively calling `positions_at` once per key is O(ledger size) per
        call; for tens of thousands of keys against a multi-million-row
        ledger that's far too slow. This instead computes cumulative
        per-(user, reserve) balances once and looks up each key via a single
        grouped `merge_asof`, which is O((keys x reserves per user) log n).

        Returns long-form rows: user, block_number, reserve,
        collateral_units, debt_units -- one row per reserve the user had
        ever touched as of that block (0-valued rows included; callers
        filter as needed).
        """
        ledger = self.ledger.sort_values(
            ["user", "reserve", "block_number", "log_index"], kind="mergesort"
        ).copy()
        grouped = ledger.groupby(["user", "reserve"], sort=False)
        ledger["scaled_collateral_cum"] = grouped["scaled_collateral"].cumsum()
        ledger["scaled_debt_cum"] = grouped["scaled_debt"].cumsum()

        touched_users = keys["user"].unique()
        pairs = ledger[ledger["user"].isin(touched_users)][
            ["user", "reserve"]
        ].drop_duplicates()
        queries = keys.merge(pairs, on="user", how="left").dropna(subset=["reserve"])

        merged = pd.merge_asof(
            queries.sort_values("block_number", kind="mergesort"),
            ledger[
                [
                    "user",
                    "reserve",
                    "block_number",
                    "scaled_collateral_cum",
                    "scaled_debt_cum",
                ]
            ].sort_values("block_number", kind="mergesort"),
            on="block_number",
            by=["user", "reserve"],
            direction="backward",
        )
        merged[["scaled_collateral_cum", "scaled_debt_cum"]] = merged[
            ["scaled_collateral_cum", "scaled_debt_cum"]
        ].fillna(0.0)
        merged = merged.rename(
            columns={
                "scaled_collateral_cum": "collateral_units",
                "scaled_debt_cum": "debt_units",
            }
        )
        # Reinflate the scaled cumulative balance by the index *at the query
        # block* (merge_asof preserves the left/`queries` frame's own
        # `block_number` here, not the matched ledger row's) -- the
        # query-time half of Track E's accrual scaling (CAS-28), same
        # per-row 1.0 fallback as `_reinflate`.
        if self.interest_index is not None and not merged.empty:
            query_timestamps = (
                merged["query_timestamp"]
                if "query_timestamp" in merged.columns
                else None
            )
            liquidity = self.interest_index.index_at_many(
                merged["reserve"],
                merged["block_number"],
                "liquidity",
                query_timestamps=query_timestamps,
            ).fillna(1.0)
            variable = self.interest_index.index_at_many(
                merged["reserve"],
                merged["block_number"],
                "variable_borrow",
                query_timestamps=query_timestamps,
            ).fillna(1.0)
            merged["collateral_units"] = (
                merged["collateral_units"].to_numpy() * liquidity.to_numpy()
            )
            merged["debt_units"] = merged["debt_units"].to_numpy() * variable.to_numpy()

        # CAS-28 H3: add stable debt on top of the variable-debt term above
        # -- independent of `interest_index` (see `_reinflate`), so this
        # runs even when the reserve-index oracle is unavailable.
        if (
            self.stable_debt_checkpoints is not None
            and not self.stable_debt_checkpoints.empty
            and not merged.empty
        ):
            stable_keys_columns = ["user", "reserve", "block_number"]
            if "query_timestamp" in merged.columns:
                stable_keys_columns.append("query_timestamp")
            merged["debt_units"] = merged["debt_units"].to_numpy() + _stable_debt_units(
                self.stable_debt_checkpoints, merged[stable_keys_columns]
            )

        # `merged` is still sorted ascending by block_number here (merge_asof
        # preserves the left frame's row order, and `queries` was passed in
        # pre-sorted) -- safe to chain a second merge_asof for the Track B
        # collateral-eligibility flag without re-sorting.
        if self.collateral_toggle.empty:
            merged["collateral_enabled"] = True
        else:
            merged = pd.merge_asof(
                merged,
                self.collateral_toggle[
                    ["user", "reserve", "block_number", "enabled"]
                ].sort_values("block_number", kind="mergesort"),
                on="block_number",
                by=["user", "reserve"],
                direction="backward",
            )
            merged["collateral_enabled"] = merged["enabled"].fillna(True)
            merged = merged.drop(columns=["enabled"])
        return merged

    def whale_positions(
        self,
        block_number: int,
        price_oracle: PriceOracle,
        timestamp: pd.Timestamp,
        top_n: int = 500,
    ) -> pd.DataFrame:
        """Rank accounts by total USD collateral value at `block_number`.

        Feeds CAS-47's "whale-position tracking for graph nodes" subtask —
        the contagion graph (CAS-23) models the top ~500 whale positions
        individually rather than only in market x asset x HF-band buckets.
        """
        positions = self.positions_at(block_number)
        if positions.empty:
            return pd.DataFrame(columns=["user", "collateral_usd", "debt_usd"])

        all_reserves = positions["reserve"].unique().tolist()
        prices = price_oracle.prices_at(all_reserves, timestamp)
        price_series = positions["reserve"].map(prices)

        positions = positions.assign(
            collateral_usd=positions["collateral_units"].clip(lower=0) * price_series,
            debt_usd=positions["debt_units"].clip(lower=0) * price_series,
        )
        by_user = positions.groupby("user", as_index=False)[
            ["collateral_usd", "debt_usd"]
        ].sum(min_count=1)
        by_user = by_user.sort_values(
            "collateral_usd", ascending=False, na_position="last"
        )
        return by_user.head(top_n).reset_index(drop=True)
