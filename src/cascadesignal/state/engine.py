def _empty_ledger_rows() -> pd.DataFrame:
    """Correctly-*typed* empty ledger frame (`block_number`/`log_index` as
    int64, `scaled_collateral`/`scaled_debt` as float64) -- a bare
    `pd.DataFrame(columns=[...])` defaults every column to `object` dtype
    with no data to infer from, which breaks `positions_at_many`'s
    `groupby(...).cumsum()` downstream (CAS-28 H3).

    `tx_hash` (CAS-28 H4-general): only ever populated on the H3 exact-ledger
    path (see `_exact_atoken_ledger_rows`/`_exact_variable_debt_ledger_rows`)
    -- needed by `position_at_log_index` to tell "an earlier event in this
    SAME liquidation's own transaction" (must stay excluded from its
    pre-state) apart from "an earlier event in a genuinely different
    transaction" (must be included). The pre-H3 `build_ledger` fallback path
    never sets this column at all; `position_at_log_index` degrades to its
    pre-fix exact-log_index cutoff there, which has no such bug (see that
    function's docstring)."""
    return pd.DataFrame(
        {
            "block_number": pd.Series(dtype="int64"),
            "log_index": pd.Series(dtype="int64"),
            "user": pd.Series(dtype="object"),
            "reserve": pd.Series(dtype="object"),
            "scaled_collateral": pd.Series(dtype="float64"),
            "scaled_debt": pd.Series(dtype="float64"),
            "tx_hash": pd.Series(dtype="object"),
        }
    )


